let _catalog: Product[] | null = null;

export function getCatalog(): Product[] {
  if (_catalog) return _catalog;
  _catalog = seedProducts.map((s, index) => {
    const cat = categories.find((c) => c.slug === s.categorySlug);
    const variants: ProductVariant[] = s.sizes.map(
      ([size, price, salePrice, stock], vIndex) => ({
        id: `var-${s.slug}-${vIndex}`,
        productId: `demo-${s.slug}`,
        size,
        price,
        salePrice,
        stock,
        sku: `${s.categorySlug.slice(0, 3).toUpperCase()}-${String(index + 1).padStart(3, "0")}${size === "Set" || size.includes("×") ? "-SET" : "-" + size.replace(/[^0-9]/g, "")}ml`,
      })
    );
    const images: ProductImage[] = s.images && s.images.length > 0
      ? s.images.map(img)
      : [img(s.slug)];
    const now = new Date(Date.now() - (seedProducts.length - index) * 86400000).toISOString();
    return {
      ...s,
      id: `demo-${s.slug}`,
      images,
      variants,
      categoryName: cat?.name ?? s.categorySlug,
      categorySlug: s.categorySlug,
      isDemo: true,
      createdAt: now,
      updatedAt: now,
    };
  });
  return _catalog!;
}

export function getDemoProducts(): Product[] {
  return getCatalog();
}

